#include "Dsp/BiosphereDSP.h"
#include <algorithm>
#include <array>
#include <chrono>
#include <cmath>
#include <iostream>
#include <stdexcept>
#include <vector>

namespace
{
constexpr int sampleRate = 48000;
constexpr double tau = 6.2831853071795864769;

void demand(bool condition, const char* reason)
{
    if (!condition) throw std::runtime_error(reason);
}

struct Render
{
    std::array<std::vector<float>, 2> audio;
    float peak = 0.0f, maxDerivative = 0.0f, maxMemory = 0.0f;
    double wetDifference = 0.0, elapsedSeconds = 0.0;
};

std::array<std::vector<float>, 2> guitar(int seconds)
{
    const int count = sampleRate * seconds;
    std::array<std::vector<float>, 2> dry;
    for (auto& channel : dry)
        channel.resize(static_cast<std::size_t>(count));
    for (int i = 0; i < count; ++i)
    {
        const double t = static_cast<double>(i) / sampleRate;
        const int phase = i % static_cast<int>(sampleRate * 0.72);
        const float pick = phase < 105
            ? 0.55f * std::exp(-static_cast<float>(phase) / 28.0f) : 0.0f;
        dry[0][static_cast<std::size_t>(i)] = static_cast<float>(
            0.22 * std::sin(tau * 196.0 * t)
            + 0.06 * std::sin(tau * 392.0 * t)) + pick;
        dry[1][static_cast<std::size_t>(i)] = static_cast<float>(
            0.19 * std::sin(tau * 196.0 * t + 0.11)
            + 0.04 * std::sin(tau * 588.0 * t)) + pick * 0.86f;
    }
    return dry;
}

enum class Change { none, pulseRate, harmonicRoot, memoryReverse, enginesOff };

Render run(std::array<std::vector<float>, 2> input,
           biosphere::Parameters params, Change change = Change::none)
{
    biosphere::BiosphereDSP dsp;
    dsp.prepare(sampleRate, 256, 2);
    Render rendered;
    rendered.audio = std::move(input);
    const auto original = rendered.audio;
    const int total = static_cast<int>(rendered.audio[0].size());
    const int changeAt = total / 2 / 256 * 256;
    auto start = std::chrono::steady_clock::now();

    for (int offset = 0; offset < total; offset += 256)
    {
        if (offset >= changeAt)
        {
            switch (change)
            {
                case Change::pulseRate: params.rateHz = 8.0f; break;
                case Change::harmonicRoot: params.rootHz = 330.0f; break;
                case Change::memoryReverse: params.memoryReverse = 1.0f; break;
                case Change::enginesOff:
                    params.pulseActive = params.harmonicActive =
                        params.mutationActive = params.memoryActive = false;
                    break;
                case Change::none: break;
            }
        }
        float* pointers[2] {
            rendered.audio[0].data() + offset,
            rendered.audio[1].data() + offset
        };
        dsp.process(pointers, 2, std::min(256, total - offset), params);
        rendered.maxMemory = std::max(rendered.maxMemory,
            dsp.getAnalysisValues().memoryActivity);
    }
    rendered.elapsedSeconds = std::chrono::duration<double>(
        std::chrono::steady_clock::now() - start).count();

    for (int ch = 0; ch < 2; ++ch)
        for (int i = 0; i < total; ++i)
        {
            const float value = rendered.audio[static_cast<std::size_t>(ch)]
                                               [static_cast<std::size_t>(i)];
            demand(std::isfinite(value), "NaN / Inf generated by sound engine");
            rendered.peak = std::max(rendered.peak, std::abs(value));
            demand(std::abs(value) <= 1.001f, "Output limiter exceeded bound");
            rendered.wetDifference += std::abs(value - original[static_cast<std::size_t>(ch)]
                                                            [static_cast<std::size_t>(i)]);
            if (i > 0)
                rendered.maxDerivative = std::max(rendered.maxDerivative,
                    std::abs(value - rendered.audio[static_cast<std::size_t>(ch)]
                                                         [static_cast<std::size_t>(i - 1)]));
        }
    return rendered;
}

void checkContinuity(const Render& rendered, int midpoint, const char* name)
{
    float worst = 0.0f;
    const int from = midpoint - 256, to = midpoint + 128;
    for (int ch = 0; ch < 2; ++ch)
        for (int i = from; i < to; ++i)
        {
            worst = std::max(worst, std::abs(
                rendered.audio[static_cast<std::size_t>(ch)][static_cast<std::size_t>(i)]
                - rendered.audio[static_cast<std::size_t>(ch)]
                                 [static_cast<std::size_t>(i - 1)]));
        }
    if (worst > 0.52f)
    {
        std::cerr << name << " discontinuity=" << worst << '\n';
        throw std::runtime_error("Abrupt waveform discontinuity at parameter change");
    }
}
} // namespace

int main()
{
    try
    {
        const auto input = guitar(4);
        const int middle = static_cast<int>(input[0].size()) / 2 / 256 * 256;

        biosphere::Parameters pulse;
        pulse.pulse = 0.96f;
        pulse.rateHz = 1.2f;
        pulse.pulseFeedback = 0.9f;
        pulse.pulseMix = 1.0f;
        pulse.harmonic = pulse.mutation = pulse.memory = 0.0f;
        pulse.mix = 0.9f;
        const auto pulseAudio = run(input, pulse, Change::pulseRate);
        demand(pulseAudio.wetDifference > 25.0,
               "PULSE PRO produced no audible rhythmic/delay effect");
        checkContinuity(pulseAudio, middle, "PULSE tempo retiming");

        biosphere::Parameters harmonic;
        harmonic.pulse = harmonic.mutation = harmonic.memory = 0.0f;
        harmonic.harmonic = 0.95f;
        harmonic.harmonicResonance = 1.0f;
        harmonic.harmonicDecay = 6.0f;
        harmonic.harmonicDamping = 0.15f;
        harmonic.harmonicMono = false;
        harmonic.rootHz = 110.0f;
        harmonic.mix = 0.95f;
        const auto harmonicAudio = run(input, harmonic, Change::harmonicRoot);
        demand(harmonicAudio.wetDifference > 25.0,
               "HARMONIC LIFE PRO produced no resonance");
        checkContinuity(harmonicAudio, middle, "HARMONIC retuning");

        biosphere::Parameters granular;
        granular.pulse = granular.harmonic = granular.memory = 0.0f;
        granular.mutation = 0.95f;
        granular.mutationDensity = 80.0f;
        granular.grainMs = 220.0f;
        granular.mutationRandom = 0.8f;
        granular.mutationPitch = 5.0f;
        granular.mutationStereo = 0.9f;
        granular.mix = 0.95f;
        const auto granularAudio = run(input, granular);
        demand(granularAudio.wetDifference > 40.0,
               "24-voice MUTATION PRO produced no audible processed signal");

        biosphere::Parameters memory;
        memory.pulse = memory.harmonic = memory.mutation = 0.0f;
        memory.memory = 0.95f;
        memory.memoryCapture = 1.0f;
        memory.memoryRecall = 0.95f;
        memory.memoryLength = 0.7f;
        memory.memoryFade = 50.0f;
        memory.memoryFeedback = 0.82f;
        memory.memoryReverse = 0.0f;
        memory.mix = 0.98f;
        const auto memoryAudio = run(input, memory, Change::memoryReverse);
        demand(memoryAudio.wetDifference > 10.0,
               "MEMORY PRO generated no real captured fragments");
        demand(memoryAudio.maxMemory > 0.10f,
               "MEMORY shared analysis did not report stored fragment activity");
        checkContinuity(memoryAudio, middle, "MEMORY reverse automation");

        biosphere::Parameters all;
        all.pulse = all.harmonic = all.mutation = all.memory = 0.85f;
        all.mutationDensity = 80.0f;
        all.grainMs = 220.0f;
        all.mix = 0.92f;
        const auto allAudio = run(input, all, Change::enginesOff);
        checkContinuity(allAudio, middle, "All four engine switches");

        // Transparent dry mode must be bit-stable regardless of active engines.
        all.mix = 0.0f;
        all.inputGain = all.outputGain = 1.0f;
        const auto transparent = run(input, all);
        double dryError = 0.0;
        for (int ch = 0; ch < 2; ++ch)
            for (std::size_t i = 0; i < input[static_cast<std::size_t>(ch)].size(); ++i)
                dryError += std::abs(transparent.audio[static_cast<std::size_t>(ch)][i]
                                     - input[static_cast<std::size_t>(ch)][i]);
        demand(dryError < 0.001, "SOUND ENGINES PRO damaged the transparent dry signal");

        std::cout << "SOUND ENGINES PRO PASS — PULSE delay crossfade, HARMONIC retune, "
                     "MUTATION 24 grains/channel, MEMORY reverse and fade, 4 enables; "
                  << "worst engine peak=" << std::max({
                         pulseAudio.peak, harmonicAudio.peak, granularAudio.peak,
                         memoryAudio.peak, allAudio.peak})
                  << ", stereo heavy-load CPU ratio="
                  << allAudio.elapsedSeconds / 4.0 << "x audio duration\n";
    }
    catch (const std::exception& e)
    {
        std::cerr << "SOUND ENGINES PRO FAIL: " << e.what() << '\n';
        return 1;
    }
    return 0;
}
